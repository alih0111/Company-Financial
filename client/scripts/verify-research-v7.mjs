import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const React=require('react');
const {renderToStaticMarkup}=require('react-dom/server');
const dest=path.resolve('node_modules/.cache/return-v7-render.cjs');
await build({entryPoints:['src/components/ResearchV7Results.tsx'],outfile:dest,bundle:true,platform:'node',format:'cjs',packages:'external',jsx:'automatic',define:{'import.meta.env.BASE_URL':'"/"'},logLevel:'error'});
const {ResearchV7View}=require(dest);
const data=JSON.parse(fs.readFileSync('public/research/return-v7.json','utf8'));
const html=renderToStaticMarkup(React.createElement(ResearchV7View,{data}));
assert.equal(data.comparison.length,6);
assert.equal(data.kaspian_decisions.length,37);
assert(html.includes('هیچ نامزد تازه‌ای'));
assert(html.includes('فروش انتها تأیید نشده'));
assert(html.includes('قابل اجرا نبود'));
assert(html.includes('کاهش تا وزن هدف'));
assert(html.includes('رتبهٔ ۱۲'));
assert(!data.method_promoted);
for(const row of data.comparison) assert(html.includes((row.final_toman/1e6).toLocaleString('fa-IR',{maximumFractionDigits:2})));
const out=process.argv[2];
if(out) fs.writeFileSync(path.join(out,'frontend_render.html'),html);
console.log('V7 actual component SSR passed: six comparisons, 37 decisions, capacity and posthoc labels');
